#!/usr/bin/env python3
"""
Writes shared/inflatable_models.lua: the inflatables that actually ship as
game models. An entry exists only when stream/<model>.ydr is present, so
the catalog never lists a model the client cannot load.

shared/holidays.lua lists these as props under their holidays (the server
allowlist) and the panel's Inflatables tab places them as props instead of
drawing the shape. Run after tools/cwconv has filled stream/.

Usage:  python tools/inflatable-models.py
Needs:  lupa (reads shared/shapes.lua for holidays and descriptions).
"""
import json, pathlib
from lupa import LuaRuntime

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "build" / "inflatables" / "manifest.json"
STREAM = ROOT / "stream"
OUT = ROOT / "shared" / "inflatable_models.lua"

lua = LuaRuntime(unpack_returned_tuples=True)
lua.execute("Config = { Holidays = {}, CustomProps = {}, Season = {} }")
lua.execute((ROOT / "shared" / "shapes.lua").read_text(encoding="utf-8"))
shapes = {s.name: s for s in lua.globals().Shapes.List.values()}


def q(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


manifest = json.loads(MANIFEST.read_text(encoding="utf-8-sig"))
rows = []
for info in manifest:
    model = info["model"]
    if not (STREAM / (model + ".ydr")).exists():
        continue
    s = shapes.get(info["shape"])
    if s is None:
        continue
    holidays = [str(h) for h in s.holidays.values()] if s.holidays else []
    rows.append((model, info["shape"], str(s.label), float(info["size"]), bool(s.arch), holidays, str(s.desc or "")))

lines = [
    "-- GENERATED by tools/inflatable-models.py from stream/ and build/inflatables/manifest.json. Do not edit.",
    "--",
    "-- The inflatables that ship as real game models (stream/*.ydr, archetypes",
    "-- in stream/sk_inflatables.ytyp): solid, lit by the engine, you can bump",
    "-- into them. shared/holidays.lua lists each under its holidays as a prop",
    "-- and the panel's Inflatables tab places that prop instead of drawing",
    "-- the shape. Must load before shared/holidays.lua.",
    "InflatableModels = {",
]
for model, shape, label, size, arch, holidays, desc in sorted(rows):
    hol = "{ " + ", ".join(q(h) for h in holidays) + " }"
    lines.append("    { model = %s, shape = %s, label = %s, size = %.1f, arch = %s, holidays = %s,"
                 % (q(model), q(shape), q(label), size, "true" if arch else "false", hol))
    lines.append("      desc = %s }," % q(desc))
lines.append("}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote %s: %d models" % (OUT.relative_to(ROOT), len(rows)))
